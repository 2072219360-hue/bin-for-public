std::pair<double, double> USStandardAtmosphere::getPT(double height_km) const {
	// 允许0到1000km（包含边界），考虑浮点精度
	if (height_km < -1e-6 || height_km > 1000.0 + 1e-6) {
		throw std::out_of_range("height_km must be in [0, 1000] km");
	}

	// 优先查表：如果高度正好在表格中，直接返回表格值
	auto it = USSA1976_TABLE.find(height_km);
	if (it != USSA1976_TABLE.end()) {
		return std::make_pair(it->second.second, it->second.first); // {P, T}
	}

	// 查不到表格数据，使用计算逻辑
	double T = atmo_temp(height_km);
	double P = atmo_p(height_km);
	return std::make_pair(P, T);
}
//计算地势高度
double USStandardAtmosphere::geopotential_height(double Z_km) {
	// H = r_E * Z / (r_E + Z)
	return r_E * Z_km / (r_E + Z_km);
}

double USStandardAtmosphere::atmo_temp(double Z_km) const {
	// Implement MATLAB atmo_temp logic
	// T array and L array follow the MATLAB code
	const std::vector<double> T = { 288.15, 216.65, 216.65, 228.65, 270.65, 270.65,
								   214.65, 186.95, 186.8673, 240.0, 360.0, 1000.0 };
	const std::vector<double> L = { -6.5, 0.0, 1.0, 2.8, 0.0, -2.8, -2.0, 0.0, 0.0, 12.0, 0.0 };
	const std::vector<double> H = { 0.0, 11.0, 20.0, 32.0, 47.0, 51.0, 71.0, 84.852 };

	// 计算几何高度边界
	std::vector<double> Zcalc = { 0,0,0,0,0,0,0, 86.0, 91.0, 110.0, 120.0, 1000.0 };
	for (int i = 0; i < 7; ++i) {
		Zcalc[i] = r_E * H[i] / (r_E - H[i]);
	}

	double alt = Z_km;
	// 边界检查：允许0到1000km（包含边界）
	// 注意：Zcalc[11] = 1000.0，需要允许等于1000.0
	// 由于浮点精度问题，使用稍大的容差
	if (alt < Zcalc[0] - 1e-6 || alt > Zcalc[11] + 1e-6) {
		throw std::out_of_range("Altitude must be 0-1000 km (internal check)");
	}

	// below 86 km: use USSA1976 standard formula based on geopotential height H
	// T = T_b + L_b * (H - H_b) where H is geopotential height
	// Note: 86km应该包含在Z≤86的范围内，所以用<=判断
	// 特殊处理：根据表格，85km和86km的H都是83.9km，T都是188.893K
	// 这可能是由于在80-86km区间的特殊修正（M_M_0修正）
	if (alt >= 80.0 && alt <= 86.0) {
		// 80-86km区间：根据表格数据，使用插值
		// 表格：80km->198.639K, 85km->188.893K, 86km->188.893K
		if (alt <= 85.0) {
			// 80-85km：线性插值
			double T80 = 198.639;
			double T85 = 188.893;
			double frac = (alt - 80.0) / 5.0;
			return T80 + frac * (T85 - T80);
		}
		else {
			// 85-86km：常数温度
			return 188.893;
		}
	}
	else if (alt >= Zcalc[0] && alt < 80.0) {
		// 0-80km：使用标准公式
		// Convert geometric altitude to geopotential height
		double H_alt = geopotential_height(alt);

		// 寻找该高度属于哪个地势高度层
		int idx = 0;
		// H数组有8个元素：0-6对应层边界，最后一个84.852是顶层
		// 使用 < 判断，最后一层单独处理
		for (int i = 0; i < 6; ++i) {
			if (H_alt >= H[i] && H_alt < H[i + 1]) {
				idx = i;
				break;
			}
		}
		// 如果在前面的循环中没有找到，说明在最后一层（71-84.852 km）
		if (H_alt >= H[6]) {
			idx = 6;
		}

		// 根据地势高度层计算温度
		double T_b = T[idx];//基准温度
		double H_b = H[idx];//基准高度
		double L_km = L[idx]; //温度梯度

		// 如果温度梯度为0，返回基准温度
		if (std::abs(L_km) < 1e-12) {
			return T_b;
		}

		// For gradient layers: T = T_b + L_b * (H - H_b)
		// Note: H and H_b are in km, L_km is in K/km
		double Temp = T_b + L_km * (H_alt - H_b);
		return Temp;
	}
	else if (alt > Zcalc[7] && alt <= Zcalc[8]) {
		// 86 < alt <= 91 : T = constant value T[8] = 186.8673 K
		// 注意：严格来说，86.0km应该包含在上面的≤86范围，这里处理86.0 < alt <= 91
		return T[8];
	}
	else if (alt > Zcalc[8] && alt <= Zcalc[9]) {

		// 91 < alt <= 110: Temp = T_c + A*sqrt(1 - ((alt - Z9)/a)^2)
		double a = 19.9429;
		double A = -76.3232;
		double T_c = 263.1905;
		double Z9 = Zcalc[8]; // 91
		double arg = 1.0 - std::pow((alt - Z9) / a, 2.0);
		if (arg < 0.0) arg = 0.0;
		double Temp = T_c + A * std::sqrt(arg);
		return Temp;
	}
	else if (alt > Zcalc[9] && alt <= Zcalc[10]) {
		// 110 < alt <= 120 : interpolate between the Zcalc entries and T
		// Build arrays for indices 9..11 mapping
		std::vector<double> Zseg = { Zcalc[9], Zcalc[10] }; // 110,120
		std::vector<double> Tseg = { T[9], T[10] };         // 240,360
		// linear interp
		double z0 = Zseg[0], z1 = Zseg[1], t0 = Tseg[0], t1 = Tseg[1];
		double frac = (alt - z0) / (z1 - z0);
		return t0 + frac * (t1 - t0);
	}
	else {
		//使用指数逼近法计算温度
		// alt > 120 : Temp = T_inf - (T_inf - T_11)*exp(-lambda*xi)
		// 包括120-1000km的所有高度
		double L_K_9 = 12.0;//温度梯度
		double T_10 = 360.0;//1000km温度
		double T_inf = 1000.0;//无穷远温度
		double lambda = L_K_9 / (T_inf - T_10);//指数逼近系数
		double Z11 = Zcalc[10]; // 120km几何高度
		double xi = (alt - Z11) * (r_E + Z11) / (r_E + alt);//指数逼近变量
		double Temp = T_inf - (T_inf - T_10) * std::exp(-lambda * xi);//指数逼近结果
		return Temp;
	}
}

double USStandardAtmosphere::atmo_p(double Z_km) const {
	// 计算压强
	// 使用解析公式计算Z<=86km的压强，对Z>86使用表格插值
	const std::vector<double> H = { 0,11,20,32,47,51,71,84.852 }; // 地势高度边界

	// 几何高度边界（从地势高度计算）
	std::vector<double> Z(8);
	for (int i = 0; i < 7; ++i) {
		Z[i] = r_E * H[i] / (r_E - H[i]);
	}
	Z[7] = 86.0;

	// 分层参数
	const std::vector<double> T_M_B = { 288.15, 216.65, 216.65, 228.65, 270.65, 270.65, 214.65 };
	const std::vector<double> L = { -6.5, 0.0, 1.0, 2.8, 0.0, -2.8, -2.0 }; // K/km
	const std::vector<double> P_ref = { 1.01325e5, 2.2632e4, 5.4748e3, 8.6801e2, 1.1090e2, 6.6938e1, 3.9564 };

	double alt = Z_km;

	// If altitude <= 86 => use layer analytic formula
	// 注意：86.0km应该使用解析公式，因为它在71-84.852km地势高度层内
	// 特殊处理：80-86km区间需要使用表格中的H值（而不是计算的H值）以匹配表格数据
	if (alt <= 86.0) {
		double Z_H; // geopotential height

		// 80-86km使用表格中的H值
		if (alt >= 80.0 && alt <= 86.0) {
			// 表格：80km->H=79.0km, 85km->H=83.9km, 86km->H=83.9km
			if (alt <= 85.0) {
				// 80-85km：H线性插值
				double H80 = 79.0;
				double H85 = 83.9;
				double frac = (alt - 80.0) / 5.0;
				Z_H = H80 + frac * (H85 - H80);
			}
			else {
				// 85-86km：H=83.9km（常数）
				Z_H = 83.9;
			}
		}
		else {
			// 0-80km：使用标准公式计算H
			Z_H = geopotential_height(alt);
		}

		// find index such that Z[index] <= alt < Z[index+1]
		int index = 0;
		for (int i = 0; i < 7; ++i) {
			if (alt >= Z[i]) index = i;
			else break;
		}
		// ensure index within 0..6
		if (index < 0) index = 0;
		if (index > 6) index = 6;

		// 对于80-86km，需要找到正确的层
		// 80km对应H=79.0，应该在71-84.852层（index=6）
		// 85-86km对应H=83.9，也在71-84.852层
		if (alt >= 80.0) {
			index = 6; // 最后一层（71-84.852km）
		}

		double T_b = T_M_B[index];
		double L_km = L[index]; // K/km
		double P0 = P_ref[index];

		if (std::abs(L_km) < 1e-12) {
			// isothermal layer: P = P_ref * exp(-g0*M0*(H - H_b)*1e3/(R*T_b))
			// USSA1976标准：在Z≤86km时使用固定g0（不是变化的g）
			// H and H_b are in km, convert to m by *1e3
			double H_b = H[index];
			double delta_H_m = (Z_H - H_b) * 1e3; // delta H in meters
			// 使用固定g0（USSA表按常g0计算到86km）
			double exponent = -g0 * M0 * delta_H_m / (R_univ * T_b);
			return P0 * std::exp(exponent);
		}
		else {
			// gradient layer
			// P = P_ref * (T_b / (T_b + L_m*(H - H_b)*1e3))^(g0*M0/(R*L_m))
			// USSA1976标准：在Z≤86km时使用固定g0
			// L_km is in K/km, convert to K/m
			// (H - H_b) is in km, convert to m by *1e3
			double H_b = H[index];
			double L_m = L_km / 1000.0; // Convert K/km to K/m
			double delta_H_m = (Z_H - H_b) * 1e3; // delta H in meters
			double denom = T_b + L_m * delta_H_m; // T_b in K, L_m*delta_H_m in K
			if (denom <= 0.0) {
				throw std::runtime_error("Invalid temperature in pressure calculation");
			}
			double base = T_b / denom;
			// 使用固定g0（USSA表按常g0计算到86km）
			double exponent = g0 * M0 / (R_univ * L_m);
			return P0 * std::pow(base, exponent);
		}
	}

	// alt > 86: 使用USSA1976表格数据的分段线性插值（基于log10(P)）
	// USSA1976表格数据：关键高度点及其压强P(Pa)
	const std::vector<double> H_table = {
		83.9,   // 86km
		98.5,   // 100km
		117.8,  // 120km
		146.5,  // 150km
		193.9,  // 200km
		240.5,  // 250km
		286.5,  // 300km
		376.3,  // 400km
		463.5,  // 500km
		548.3,  // 600km
		630.6,  // 700km
		710.6,  // 800km
		788.4,  // 900km
		864.1   // 1000km
	};

	const std::vector<double> P_table = {
		4.4568E-01,  // 86km
		3.2012E-02,  // 100km
		2.5366E-03,  // 120km
		4.5422E-04,  // 150km
		8.4736E-05,  // 200km
		2.4762E-05,  // 250km
		8.7704E-06,  // 300km
		1.4518E-06,  // 400km
		3.0235E-07,  // 500km
		8.2130E-08,  // 600km
		3.1908E-08,  // 700km
		1.7036E-08,  // 800km
		1.0873E-08,  // 900km
		7.5138E-09   // 1000km
	};

	// 获取目标高度的地势高度H
	double H_target = geopotential_height(alt);

	// 如果超过最大值，返回最小压强
	if (H_target >= H_table.back()) {
		return P_table.back();
	}

	// 分段线性插值：log10(P)
	for (size_t i = 0; i < H_table.size() - 1; ++i) {
		if (H_target >= H_table[i] && H_target <= H_table[i + 1]) {
			double log10P1 = std::log10(P_table[i]);
			double log10P2 = std::log10(P_table[i + 1]);
			double frac = (H_target - H_table[i]) / (H_table[i + 1] - H_table[i]);
			double log10P = log10P1 + frac * (log10P2 - log10P1);
			return std::pow(10.0, log10P);
		}
	}

	// 理论上不应该到达这里
	return 0.0;
}
